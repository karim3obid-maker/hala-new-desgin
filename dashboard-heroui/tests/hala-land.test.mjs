import assert from 'node:assert/strict';
import {defaultStore,emptyPage,validateStore,validatePage,validateImageFiles,validOffer,maxImageSize,normalizePage} from '../src/services/halaLandValidation.js';
import {landAddressPolicy,saudiRegions} from '../src/data/saudiRegions.js';
import {normalizeSaudiPhone,validateDraft} from '../src/data/draftEditor.js';
const store={...defaultStore,name:'متجر اختبار',slug:'test-store'};
assert.deepEqual(validateStore(store),{});
assert.deepEqual(validateStore({...store,formPlacement:'separate'}),{});
assert.ok(validateStore({...store,formPlacement:'unknown'}).formPlacement);
assert.ok(validateStore({...store,cod:false}).payment);
assert.ok(validateStore({...store,showWhatsapp:true}).whatsapp);
assert.ok(validateStore({...store,metaEnabled:true,metaPixel:'abc'}).metaPixel);
assert.ok(validateStore({...store,tiktokEnabled:true,tiktokPixel:'<script>'}).tiktokPixel);
assert.ok(validateStore({...store,instagram:'javascript:alert(1)'}).instagram);
assert.ok(validateStore({...store,slug:'invalid slug'}).slug);
assert.deepEqual(validateStore({...store,paymob:true,metaEnabled:true,metaPixel:'123456789',tiktokEnabled:true,tiktokPixel:'ABC123456789',whatsapp:'+966512345678',showWhatsapp:true}),{});
const products=[{id:'product-1',cost:15}];
const page={...emptyPage(),id:'page-1',name:'صفحة اختبار',slug:'offer',productId:'product-1',quantity:'2',price:'99.95',images:[{id:'image-1'}]};
assert.deepEqual(validatePage(page,[],products),{});
assert.ok(validatePage({...page,id:'page-2'},[page],products).slug);
assert.deepEqual(validatePage(page,[page],products),{});
for(const [key,value] of [['images',[]],['productId','missing'],['price','0'],['quantity','1.5'],['price','10.999'],['quantity','1000'],['name','']])assert.ok(Object.keys(validatePage({...page,[key]:value},[],products)).length,key);
assert.equal(validOffer('1','10.50'),true);
assert.throws(()=>validateImageFiles([{type:'image/svg+xml',size:100}]));
assert.throws(()=>validateImageFiles([{type:'image/png',size:maxImageSize+1}]));
assert.throws(()=>validateImageFiles([{type:'image/png',size:10}],20));
assert.throws(()=>validateImageFiles([{type:'image/png',size:0}]));
assert.doesNotThrow(()=>validateImageFiles([{type:'image/webp',size:maxImageSize}],19));
const values={name:'عميل الاختبار',phone:'٠٥١٢٣٤٥٦٧٨',altPhone:'',region:'الرياض',city:'الرياض',district:'النخيل',address:'شارع الاختبار مبنى 12',nationalAddress:'ABPE3294'};
assert.equal(normalizeSaudiPhone(values.phone),'+966512345678');
assert.deepEqual(validateDraft(values,[{id:'product-1',quantity:2}],{mode:'cod',codTotal:'99.95'}),{});
assert.ok(validateDraft({...values,phone:'123'},[{quantity:2}],{mode:'cod',codTotal:'99.95'}).phone);
console.log('Hala Land: store/payment/pixel/URL validation, offers, duplicate slugs, image limits and Saudi form checks passed.');
const multi={...page,offers:[{id:'a',quantity:'1',price:'99'},{id:'b',quantity:'3',price:'249'}]};
assert.deepEqual(validatePage(multi,[],products),{});
assert.ok(validatePage({...multi,offers:[multi.offers[0],{...multi.offers[1],quantity:'1'}]},[],products).offer);
assert.ok(validatePage({...multi,settings:{ctaText:''}},[],products).ctaText);
assert.ok(validatePage({...multi,settings:{expiresAt:'not-a-date'}},[],products).expiresAt);

const template=normalizePage(page);
assert.equal(template.template,'sitar');
assert.equal(template.content.warranty,'');
assert.equal(template.content.faqs.length,0);
const customized={...template,content:{...template.content,title:'عنوان المنتج',benefits:'ميزة أولى\nميزة ثانية',faqs:[{question:'كيف أختار العرض؟',answer:'راجع الكمية والإجمالي قبل التأكيد.'}]}};
assert.deepEqual(validatePage(customized,[],products),{});
assert.equal(normalizePage(customized).content.title,'عنوان المنتج');
assert.equal(normalizePage(page).content.title,'');
assert.ok(validatePage({...customized,content:{...customized.content,faqs:[{question:'سؤال',answer:''}]}},[],products).content);
assert.ok(validatePage({...customized,content:{...customized.content,title:'x'.repeat(161)}},[],products).content);
console.log('Sitar template: legacy drafts retain data, content is independent, policies default empty, FAQ and text bounds validated.');

// Removing city in Hala Land must not weaken the standard order editor's address rules.
const noCity={...values,city:''};
const codPricing={mode:'cod',codTotal:'33'};
const selectedProduct=[{...products[0],quantity:3}];
assert.ok(validateDraft(noCity,selectedProduct,codPricing).city);
assert.deepEqual(validateDraft(noCity,selectedProduct,codPricing,{requireCity:false}),{});
assert.ok(validateDraft({...noCity,phone:'123'},selectedProduct,codPricing,{requireCity:false}).phone);
assert.ok(validateDraft({...noCity,region:''},selectedProduct,codPricing,{requireCity:false}).region);
console.log('Hala Land no-city checkout: valid address accepted, Saudi phone and region still required; standard order editor still requires city.');

const stackedValues={...values,city:'',district:'',notes:''};
assert.equal(saudiRegions.length,13);
assert.equal(new Set(saudiRegions).size,13);
assert.deepEqual(validateDraft(stackedValues,selectedProduct,codPricing,landAddressPolicy),{});
assert.ok(validateDraft({...stackedValues,region:'منطقة غير موجودة'},selectedProduct,codPricing,landAddressPolicy).region);
assert.ok(validateDraft({...stackedValues,nationalAddress:'bad'},selectedProduct,codPricing,landAddressPolicy).nationalAddress);
assert.ok(validateDraft(stackedValues,selectedProduct,codPricing).district);
console.log('Stacked checkout: Saudi region whitelist and optional national address validated; standard order district requirement preserved.');
